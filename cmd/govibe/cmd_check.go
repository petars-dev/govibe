func init() {
	rootCmd.AddCommand(checkCmd)
	f := checkCmd.Flags()
	f.String("root", ".", "the project root: the directory holding go.mod")
	f.String("fail-on", "error", "exit 1 when there is a finding at or above this severity that the baseline does not accept: error, warning, info or none")
	f.String("baseline", "", "file of accepted findings (default: the profile's graph directory, docs/graph/baseline.json, when the file exists)")
	f.String("format", "text", "output: text, json, or github (text plus workflow annotations for the new findings)")
	f.Bool("no-inspect", false, "do not run the app's `inspect --json` for its routes and commands (the rules that need them do not run)")
	f.Bool("git", false, "also index last commit, churn and co-change from `git log`")
	f.Bool("verbose", false, "log every layer as it is indexed")
	checkCmd.SilenceUsage = true
	checkCmd.SilenceErrors = true
}

var checkCmd = &cobra.Command{
	Use:   "check",
	Short: "Check the project: the managed files, then the graph gate in a scratch store",
	Long: `Check the project the way CI does. First the files the framework generated (the
Makefile, .air.toml, the workflow, the managed block of SKILL.md) are compared with the
manifest in govibe.yml, and an edited or missing one is reported. Then the project is
indexed into a scratch graph store with the calls layer on (as "govibe graph index
--calls" does, with the app's own routes and commands from its "inspect --json"), and
the gate is applied: a finding at or above --fail-on that the baseline does not accept
fails the check, and so does a baseline entry without a reason. A new app has no finding
at any severity.

An invalid schedule, or any other boot error of the app, fails the check with the
command the app named. Run it as "go tool govibe check" inside the app, so the tool that
judges the project is the version pinned in its go.mod.

Exit status: 0 when the gate passes, 1 on a new finding, 2 when the check itself could not
run (the app does not build, a layer failed, a bad flag).`,
	Example: `  go tool govibe check
  go tool govibe check --fail-on info      # no finding at any severity
  go tool govibe check --format github     # in a workflow: annotations on the findings`,
	Args: cobra.NoArgs,
	RunE: func(cmd *cobra.Command, args []string) error {
		o := checkOptions{}
		f := cmd.Flags()
		o.root, _ = f.GetString("root")
		o.failOn, _ = f.GetString("fail-on")
		o.baseline, _ = f.GetString("baseline")
		o.format, _ = f.GetString("format")
		o.noInspect, _ = f.GetBool("no-inspect")
		o.git, _ = f.GetBool("git")
		if verbose, _ := f.GetBool("verbose"); verbose {
			logrus.SetLevel(logrus.InfoLevel)
		} else {
			logrus.SetLevel(logrus.ErrorLevel)
		}
		o.openSchema = func() (func(context.Context) (*dbexplorer.Snapshot, error), func(), string) {
			return schemaFromConfig(o.root)
		}
		err := runCheck(cmd.Context(), o, cmd.OutOrStdout(), cmd.ErrOrStderr())
		var ee *exitError
		if err != nil && !errors.As(err, &ee) {
			return &exitError{code: 2, msg: "check: " + err.Error()}
		}
		return err
	},
}

// checkOptions are the flags of `govibe check`, plus the seams the tests use.
type checkOptions struct {
	root, failOn, baseline, format string
	noInspect, git                 bool

	inspect    func(ctx context.Context, root string) (*routeinfo.Inspect, error)
	openSchema func() (func(context.Context) (*dbexplorer.Snapshot, error), func(), string)
}

func runCheck(ctx context.Context, o checkOptions, out, errOut io.Writer) error {
	prof, err := profile.Load(o.root)
	if err != nil {
		return err
	}
	switch o.format {
	case "text", "json", "github":
	default:
		return fmt.Errorf("unknown --format %q: use text, json or github", o.format)
	}
	notes := out
	if o.format == "json" {
		notes = errOut // stdout stays the one JSON document of the gate
	}
	root, _ := filepath.Abs(o.root)
	fmt.Fprintf(notes, "govibe check: %s\n", root)
	drift := scaffold.CheckManaged(o.root, prof.Managed)
	switch {
	case prof.Managed == nil:
		fmt.Fprintln(notes, "managed files: none (no manifest in govibe.yml: the project was not generated by govibe new)")
	case len(drift) == 0:
		fmt.Fprintf(notes, "managed files: %d as generated (framework %s)\n", len(prof.Managed.Files), prof.Managed.Version)
	default:
		fmt.Fprintf(notes, "managed files: %d of %d not as generated (framework %s)\n", len(drift), len(prof.Managed.Files), prof.Managed.Version)
		for _, d := range drift {
			fmt.Fprintf(notes, "  %s\n", d)
		}
	}
	fmt.Fprintln(notes)

	baseline := o.baseline
	if baseline == "" {
		if p := filepath.Join(o.root, filepath.FromSlash(prof.Graph.Dir), "baseline.json"); fileExists(p) {
			baseline = p
		}
	}
	// A scratch store: the check never touches the store a dev server holds.
	dir, err := os.MkdirTemp("", "govibe-check-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(dir)
	gi := graphIndexOptions{root: o.root, dir: dir, calls: true, git: o.git, failOn: o.failOn, baseline: baseline, noInspect: o.noInspect, format: o.format,
		openSchema: o.openSchema}
	if o.inspect != nil {
		gi.inspect = o.inspect
	}
	return runGraphIndex(ctx, gi, out, errOut)
}

func fileExists(p string) bool {
	st, err := os.Stat(p)
	return err == nil && !st.IsDir()
}
