// ManagedChange is what an upgrade does to one managed file.
type ManagedChange struct {
	File string
	// State: "unchanged", "updated" (not edited by the app, rewritten), "restored" (it
	// was missing), "created" (a managed file this version adds), "edited" (the app
	// changed it: refused) or "forced" (edited, overwritten on --force).
	State string
	// Diff is the unified diff from the file as it is to what is written, "" when nothing changes.
	Diff    string
	content []byte
}

// Changes reports whether the file is written.
func (c ManagedChange) Changes() bool {
	return c.State == "updated" || c.State == "restored" || c.State == "created" || c.State == "forced"
}

// Upgrade is the plan `govibe upgrade` makes: the managed files re-rendered for the
// framework version the app's go.mod pins, compared with the files on disk and with
// the manifest, and the manifest that records the result.
type Upgrade struct {
	Root string
	// From is the framework version the manifest records; To is the one go.mod pins.
	From, To string
	Changes  []ManagedChange
	// Refused lists the edited files the plan will not overwrite (none with Force).
	Refused  []string
	manifest []byte // the new govibe.yml
	oldYML   []byte
}

// PlanUpgrade reads the project at root and plans its upgrade. Nothing is written.
func PlanUpgrade(root string, force bool) (*Upgrade, error) {
	abs, err := filepath.Abs(root)
	if err != nil {
		return nil, err
	}
	prof, err := profile.Load(abs)
	if err != nil {
		return nil, err
	}
	if prof.Managed == nil {
		return nil, fmt.Errorf("%s was not generated by govibe new (govibe.yml has no managed section), so there are no managed files to upgrade", abs)
	}
	module, version, err := pinnedFramework(abs, prof.FrameworkModule())
	if err != nil {
		return nil, err
	}
	o := Options{Module: module, Name: AppName(abs, module), FrameworkModule: prof.FrameworkModule(), FrameworkVersion: version}
	if err := o.Complete(); err != nil {
		return nil, err
	}
	tree, err := Render(o)
	if err != nil {
		return nil, err
	}
	u := &Upgrade{Root: abs, From: prof.Managed.Version, To: version}
	for _, name := range Managed {
		c, err := planFile(abs, name, tree[name], prof.Managed.Files[name], force)
		if err != nil {
			return nil, err
		}
		if c.State == "edited" {
			u.Refused = append(u.Refused, name)
		}
		u.Changes = append(u.Changes, c)
	}
	u.oldYML, err = os.ReadFile(filepath.Join(abs, profile.File))
	if err != nil {
		return nil, err
	}
	block, err := ManagedBlock(version, tree)
	if err != nil {
		return nil, err
	}
	u.manifest = replaceManagedBlock(u.oldYML, block)
	return u, nil
}

// pinnedFramework is the app's module path and the framework version its go.mod
// requires; "v0.0.0" when a replace points the framework at a checkout.
func pinnedFramework(root, framework string) (module, version string, err error) {
	b, err := os.ReadFile(filepath.Join(root, "go.mod"))
	if err != nil {
		return "", "", fmt.Errorf("%s is not the root of a Go module (no go.mod)", root)
	}
	mf, err := modfile.Parse("go.mod", b, nil)
	if err != nil {
		return "", "", fmt.Errorf("go.mod: %w", err)
	}
	if mf.Module == nil {
		return "", "", errors.New("go.mod has no module line")
	}
	for _, r := range mf.Replace {
		if r.Old.Path == framework {
			return mf.Module.Mod.Path, "v0.0.0", nil
		}
	}
	for _, r := range mf.Require {
		if r.Mod.Path == framework {
			return mf.Module.Mod.Path, r.Mod.Version, nil
		}
	}
	return "", "", fmt.Errorf("go.mod does not require %s: bump the framework first (go get %s@<version> && go mod tidy)", framework, framework)
}

// planFile compares one managed file with what the new version renders.
func planFile(root, name string, rendered []byte, recorded string, force bool) (ManagedChange, error) {
	c := ManagedChange{File: name}
	cur, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(name)))
	switch {
	case errors.Is(err, fs.ErrNotExist):
		c.State, c.content = "restored", rendered
		if recorded == "" {
			c.State = "created"
		}
		c.Diff = Diff(name, nil, rendered)
		return c, nil
	case err != nil:
		return c, err
	}
	want := rendered
	edited := false
	if name == "SKILL.md" {
		// Only the block is the framework's: the rest of the file is the app's and stays.
		newBlock, err := Block(rendered)
		if err != nil {
			return c, err
		}
		if _, err := Block(cur); err == nil {
			want = replaceBlockIn(cur, newBlock)
		} else {
			edited = true // no markers: the app rewrote the file; --force puts the block at the top
			want = append([]byte(newBlock+"\n\n"), cur...)
		}
	}
	got, err := Hash(name, cur)
	if err != nil || (recorded != "" && got != recorded) || (recorded == "" && !bytes.Equal(cur, want)) {
		edited = true
	}
	switch {
	case bytes.Equal(cur, want):
		c.State = "unchanged"
		return c, nil
	case edited && !force:
		c.State = "edited"
	case edited:
		c.State = "forced"
	default:
		c.State = "updated"
	}
	c.content = want
	c.Diff = Diff(name, cur, want)
	return c, nil
}

// replaceBlockIn swaps the managed block of a SKILL.md for newBlock and keeps the rest.
func replaceBlockIn(cur []byte, newBlock string) []byte {
	s := string(cur)
	i := strings.Index(s, BlockStart)
	j := strings.Index(s[i:], BlockEnd)
	return []byte(s[:i] + newBlock + s[i+j+len(BlockEnd):])
}

// ManagedBlock is the `managed:` section of govibe.yml for version and the managed
// files of tree.
func ManagedBlock(version string, tree Tree) (string, error) {
	var b strings.Builder
	fmt.Fprintf(&b, "managed:\n  version: %s\n  files:\n", version)
	for _, name := range Managed {
		content, ok := tree[name]
		if !ok {
			return "", fmt.Errorf("the managed file %s was not rendered", name)
		}
		h, err := Hash(name, content)
		if err != nil {
			return "", err
		}
		fmt.Fprintf(&b, "    %s: %s\n", name, h)
	}
	return b.String(), nil
}

// managedRe matches the managed section: the key at column one and every indented or
// blank line after it, up to the next top-level line.
var managedRe = regexp.MustCompile(`(?m)^managed:[^\n]*\n(?:(?:[ \t][^\n]*|)\n?)*`)

// replaceManagedBlock swaps the managed section of a govibe.yml for block, or appends
// it; the rest of the file (the app's own keys and comments) is kept as it is.
func replaceManagedBlock(yml []byte, block string) []byte {
	if loc := managedRe.FindIndex(yml); loc != nil {
		out := string(yml[:loc[0]]) + block
		rest := strings.TrimLeft(string(yml[loc[1]:]), "\n")
		if rest != "" {
			out += "\n" + rest
		}
		return []byte(out)
	}
	text := strings.TrimRight(string(yml), "\n")
	if text != "" {
		text += "\n\n"
	}
	return []byte(text + block)
}

// ManifestChanges reports whether govibe.yml would change.
func (u *Upgrade) ManifestChanges() bool { return !bytes.Equal(u.oldYML, u.manifest) }

// Apply writes the plan: every file that changes, then the manifest. A plan with
// refused files is not applied.
func (u *Upgrade) Apply() error {
	if len(u.Refused) > 0 {
		return fmt.Errorf("%d edited %s not overwritten: %s (--force overwrites)", len(u.Refused), pluralize(len(u.Refused), "file", "files"), strings.Join(u.Refused, ", "))
	}
	for _, c := range u.Changes {
		if !c.Changes() {
			continue
		}
		fp := filepath.Join(u.Root, filepath.FromSlash(c.File))
		if err := os.MkdirAll(filepath.Dir(fp), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(fp, c.content, 0o644); err != nil {
			return err
		}
	}
	if u.ManifestChanges() {
		return os.WriteFile(filepath.Join(u.Root, profile.File), u.manifest, 0o644)
	}
	return nil
}

func pluralize(n int, one, many string) string {
	if n == 1 {
		return one
	}
	return many
}

// Note is one section of the upgrade notes.
type Note struct {
	Version string // "Unreleased" or a version
	Text    string
}

// UpgradeNotes are the sections of the framework's UPGRADING doc that apply when going
// from one version to another: every released version after `from` up to `to`, and the
// unreleased section when `to` is not a release (a commit, or a checkout).
func UpgradeNotes(from, to string) ([]Note, error) {
	doc, err := frameworkdocs.Embedded().Read("upgrading")
	if err != nil {
		return nil, err
	}
	var notes []Note
	for _, sec := range strings.Split("\n"+doc, "\n## ")[1:] {
		title, body, _ := strings.Cut(sec, "\n")
		title = strings.TrimSpace(title)
		body = strings.TrimSpace(body)
		switch {
		case strings.EqualFold(title, "unreleased"):
			if semver.Prerelease(to) != "" || to == "v0.0.0" || !semver.IsValid(to) {
				notes = append(notes, Note{Version: "Unreleased", Text: body})
			}
		case semver.IsValid(title):
			if (!semver.IsValid(from) || semver.Compare(title, from) > 0) && semver.Compare(title, to) <= 0 {
				notes = append(notes, Note{Version: title, Text: body})
			}
		}
	}
	return notes, nil
}
